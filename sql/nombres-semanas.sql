create table if not exists public.nombres_semanas (
  id bigint generated by default as identity primary key,
  curso text not null,
  unidad integer not null check (unidad between 1 and 4),
  semana integer not null check (semana between 1 and 4),
  nombre text not null default '',
  actualizado_en timestamptz not null default now(),
  constraint nombres_semanas_ubicacion_unica unique (curso, unidad, semana)
);

alter table public.nombres_semanas enable row level security;
drop policy if exists "todos leen nombres de semanas" on public.nombres_semanas;
drop policy if exists "dueno guarda nombres de semanas" on public.nombres_semanas;
drop policy if exists "dueno modifica nombres de semanas" on public.nombres_semanas;
create policy "todos leen nombres de semanas"
  on public.nombres_semanas for select to anon, authenticated using (true);
create policy "dueno guarda nombres de semanas"
  on public.nombres_semanas for insert to authenticated with check (public.es_dueno());
create policy "dueno modifica nombres de semanas"
  on public.nombres_semanas for update to authenticated using (public.es_dueno()) with check (public.es_dueno());

grant select on public.nombres_semanas to anon, authenticated;
grant insert, update on public.nombres_semanas to authenticated;
grant usage, select on sequence public.nombres_semanas_id_seq to authenticated;
